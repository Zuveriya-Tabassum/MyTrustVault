"""Regenerates sql/schema_postgres.sql from the models: python -m tools.dump_schema"""
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable, CreateIndex
from app.db import Base, PG_TRIGGERS

out = ["-- GENERATED by tools/dump_schema.py. The app also creates this itself on startup (RUN_MIGRATIONS=1).\n"]
for t in Base.metadata.sorted_tables:
    out.append(str(CreateTable(t).compile(dialect=postgresql.dialect())).strip() + ";\n")
    for ix in t.indexes:
        out.append(str(CreateIndex(ix).compile(dialect=postgresql.dialect())).strip() + ";\n")
out.append("-- Append-only protection for the audit table (second layer after DB role grants):")
out += [s + ";" for s in PG_TRIGGERS]
open("sql/schema_postgres.sql", "w").write("\n".join(out) + "\n")
print("written sql/schema_postgres.sql")
